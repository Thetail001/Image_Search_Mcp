#!/usr/bin/env bash
#
# 一键验收。任何一步不过就非零退出。
#
#   ./check.sh                 # 全部（含反向测试，几分钟）
#   ./check.sh --fast          # 跳过反向测试，只跑单元测试与门禁自检
#   ./check.sh --reverse-only  # 只跑反向测试
#
# 这个脚本自己也是一道门禁，所以它有两个刻意的设计：
#
# 1. **不用 `set -e`**。`set -e` 会让"命令返回非零"和"检查不通过"混为一谈 ——
#    而 `git check-ignore` 在"没有匹配"时本来就返回 1，那是个正常结果。
#    每一步都显式判断退出码，顺手把"为什么红"打出来。
# 2. **反向测试是默认项，不是可选项**。一个永不失败的门禁比没有门禁更糟：
#    它看起来有人在看着。所以默认就要证明"注入缺陷时会红"。

set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")" || exit 2

FAST=0
REVERSE_ONLY=0
for arg in "$@"; do
  case "$arg" in
    --fast) FAST=1 ;;
    --reverse-only) REVERSE_ONLY=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "未知参数：$arg" >&2; exit 2 ;;
  esac
done

# ---------------------------------------------------------------------------
# 解释器
# ---------------------------------------------------------------------------

# PY 一律取**绝对路径**。下面有几步会在临时副本里起子进程（反向测试还会换工作目录），
# 相对路径换过目录就不再有效；而没有 .venv 时原实现留的是裸 `python3`，到调用处
# 再拼 `$(pwd)/python3` 必然是 FileNotFoundError —— CI 恰好没有 .venv，
# 本地有 .venv 反而把这个 bug 遮住了（复核报告第 12 问已在临时副本里复现）。
if [[ -x .venv/bin/python ]]; then
  PY="$(pwd)/.venv/bin/python"
elif command -v python3 >/dev/null 2>&1; then
  PY="$(command -v python3)"
else
  echo "找不到 Python 解释器" >&2
  exit 2
fi

FAILED_STEPS=()
PASSED_STEPS=()

step() {  # step <名字> <命令...>
  local name="$1"; shift
  echo
  echo "── $name"
  echo "   \$ $*"
  # 退出码必须在**紧邻的那条命令**之后取。写成 ``if "$@"; then ... fi`` 再读 ``$?``，
  # 拿到的是 if 复合命令自己的状态 —— POSIX 规定条件为假且没有 else 分支时它是 0，
  # 于是任何失败都被印成"退出码 0"，``return`` 也返回 0，报出来的原因是假的（实测踩过）。
  local code=0
  "$@" || code=$?
  if [[ $code -eq 0 ]]; then
    PASSED_STEPS+=("$name")
    echo "   → 通过"
    return 0
  fi
  FAILED_STEPS+=("$name（退出码 $code）")
  echo "   → 不通过（退出码 $code）"
  return "$code"
}

echo "仓库：$(pwd)"
echo "解释器：$PY ($("$PY" -V 2>&1))"
echo "提交：$(git rev-parse --short HEAD 2>/dev/null || echo '（无 git）')" \
     "$(git rev-parse --abbrev-ref HEAD 2>/dev/null || true)"

# ---------------------------------------------------------------------------
# 1. 代码能被导入（最快的一道，捕获语法错误）
# ---------------------------------------------------------------------------

if [[ $REVERSE_ONLY -eq 0 ]]; then

  step "模块可导入" "$PY" -c "import image_search_mcp, image_search_mcp.main, image_search_mcp.safe_download, image_search_mcp.credentials, image_search_mcp.params; print('ok')"

  # -------------------------------------------------------------------------
  # 2. 单元测试
  # -------------------------------------------------------------------------

  step "单元测试" "$PY" -m pytest -q --timeout=30 --timeout-method=thread

  # -------------------------------------------------------------------------
  # 3. 门禁自检：没有测试源码被 git 忽略
  # -------------------------------------------------------------------------

  # 这道门禁自己带反向自检（工具内部造一个被忽略的测试文件，确认它会报警）。
  # 早期版本是在这里用一句 `git ls-files` 现写的，没有自检、而且写宽了 ——
  # 每次都被 tests/__pycache__/*.pyc 误报，那种门禁只会被关掉。
  step "门禁自检：测试源码未被 git 忽略（含反向自检）" \
      "$PY" tools/gate_tests_not_ignored.py --self-test
  step "门禁自检：当前仓库无被忽略的测试源码" \
      "$PY" tools/gate_tests_not_ignored.py

  # -------------------------------------------------------------------------
  # 3b. 门禁自检：本脚本自己上报的退出码是真的
  # -------------------------------------------------------------------------

  # 这道门禁测的是**这个脚本**：step() 早先在 if 之后才读 $?，于是任何失败都被
  # 印成"退出码 0"（POSIX：if 无 else 且条件为假时状态为 0）。判定是对的，
  # 原因是错的 —— 而人排查时看的正是那个原因。工具内部带反向自检。
  step "门禁自检：check.sh 上报的退出码是真的（含反向自检）" \
      "$PY" tools/gate_check_sh_exit_code.py

  # -------------------------------------------------------------------------
  # 3b-2. 门禁自检：check.sh 选出来的解释器是可用绝对路径
  # -------------------------------------------------------------------------

  # 没有 .venv 时 PY 曾是裸 python3，调用处又拼成 $(pwd)/python3 →
  # CI（恰好没有 .venv）里直接 FileNotFoundError；本机有 .venv 所以看不到。
  # 门禁真跑两种布局，并检查调用处没有再把路径拼起来；内部带反向自检。
  step "门禁自检：check.sh 的解释器是绝对路径（含反向自检）" \
      "$PY" tools/gate_check_sh_interpreter.py

  # -------------------------------------------------------------------------
  # 3c. 部署脚本动的是线上真正在跑的那个单元
  # -------------------------------------------------------------------------

  # 这类缺陷不会自己暴露：脚本每步都成功、退出码 0，但重启的不是真正在跑的服务。
  # 桩掉 sudo/systemctl 真跑脚本，断言它重启的单元名；工具内部带反向自检。
  step "门禁：部署脚本的单元名与线上一致（含反向自检）" \
      "$PY" tools/gate_deploy_script_unit.py

  # -------------------------------------------------------------------------
  # 3d. 文档里的状态段是刚生成的，不是过期数字
  # -------------------------------------------------------------------------

  # 那一段写的是测试条数/注入条数/源码行数这类"能从产物取到的事实"。
  # 实测踩过：改了测试忘了重生成，文档一直写着旧数字（367 vs 实际 390），
  # 还漏掉一个新增的测试文件。过期的入口文档比空白更糟——它会让人按错的数字去排查。
  step "门禁：文档状态段与产物一致（含反向自检）" \
      "$PY" tools/gate_status_block_fresh.py --self-test

fi

# ---------------------------------------------------------------------------
# 4. 反向测试：证明门禁会红
# ---------------------------------------------------------------------------

if [[ $FAST -eq 0 ]]; then
  # PY 本身已经是绝对路径（见文件顶部），直接传即可 —— 不要再拼 $(pwd)：
  # 没有 .venv 的布局下那会拼出一个不存在的路径（CI 就是这种布局）。
  step "反向测试（把缺陷放回去，确认门禁会红）" \
      "$PY" tools/reverse_tests/run.py --python "$PY" || true
fi

# ---------------------------------------------------------------------------
# 汇总
# ---------------------------------------------------------------------------

echo
echo "=============================================================="
echo "通过 ${#PASSED_STEPS[@]} 步"
for name in "${PASSED_STEPS[@]:-}"; do
  [[ -n "$name" ]] && echo "  可以 $name"
done

if [[ ${#FAILED_STEPS[@]} -gt 0 ]]; then
  echo "不通过 ${#FAILED_STEPS[@]} 步："
  for name in "${FAILED_STEPS[@]}"; do
    echo "  不行 $name"
  done
  exit 1
fi

echo "全部通过。"
